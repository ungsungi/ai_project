# 선택한 관광지 정보 출력
for spot in tour_spots:
    if spot["name"] == selected_spot_name:
        st.info(f"### 🚇 가까운 지하철역: {spot['station']}")
        st.write(f"**놀거리/특징:** {spot['info']}")
