# 지도 생성 (CartoDB positron으로 깔끔한 색상 적용)
m = folium.Map(location=[37.5665, 126.9780], zoom_start=12, tiles="CartoDB positron")

# 마커 추가
for spot in tour_spots:
    folium.Marker(
        location=spot["coords"],
        popup=f"<b>{spot['name']}</b>",
        tooltip=spot["name"],
        icon=folium.Icon(color="red", icon="info-sign")
    ).add_to(m)

# 지도 크기 60% 수준으로 조정 (width=600, height=400)
st_folium(m, width=600, height=400)

# 하단 정보 설명
